#!/usr/bin/env node
// Generates scripts/migrate.sql from the JSON "database" in ../data.
// Loads: levels (from _list.json order + each <slug>.json), pending (_pending.json),
// and config singletons (_levelMonth.json, _levelVerif.json).
// Editors are intentionally NOT migrated (their API-key hashes aren't in the JSON).
//
// Run:  node scripts/build-migration.js
// Then import scripts/migrate.sql into D1 (see the header printed in the file).

const fs = require('fs');
const path = require('path');

const DATA = path.join(__dirname, '..', 'data');
const OUT = path.join(__dirname, 'migrate.sql');

const readJSON = (f) => JSON.parse(fs.readFileSync(path.join(DATA, f), 'utf8'));

// SQL literal helpers
const q = (v) => "'" + String(v).replace(/'/g, "''") + "'";      // quoted string
const s = (v) => v === undefined || v === null ? "''" : q(v);     // string, '' if missing
const jn = (v) => v === undefined || v === null ? 'NULL' : q(JSON.stringify(v)); // json col
const num = (v) => v === undefined || v === null || v === '' ? 'NULL' : Number(v);
const bit = (v) => (v ? 1 : 0);

// NOTE: no `password` / `difficulty` — those aren't in the JSON and aren't
// columns on the real `levels` table (they came from a reconstructed Worker).
const LEVEL_COLS = [
  'path', 'name', 'author', 'creators', 'verifier', 'verification', 'showcase',
  'thumbnail', 'frameCounter', 'id', 'rating',
  'length', 'percentToQualify', 'percentFinished', 'lastUpd', 'tags',
  'records', 'run', 'isVerified', 'isMain', 'isFuture', 'benchmark', 'sort_order',
];

function levelValues(slug, j, order) {
  return [
    q(slug),                         // path
    s(j.name),                       // name
    s(j.author),                     // author
    jn(j.creators || []),            // creators
    s(j.verifier),                   // verifier
    s(j.verification),               // verification
    s(j.showcase),                   // showcase
    s(j.thumbnail),                  // thumbnail
    j.frameCounter ? q(j.frameCounter) : 'NULL', // frameCounter
    s(j.id),                         // id (stored as text)
    num(j.rating),                   // rating
    num(j.length),                   // length
    num(j.percentToQualify),         // percentToQualify
    num(j.percentFinished),          // percentFinished
    s(j.lastUpd),                    // lastUpd
    jn(j.tags || []),                // tags
    jn(j.records || []),             // records
    jn(j.run || []),                 // run
    bit(j.isVerified),               // isVerified
    bit(j.isMain),                   // isMain
    bit(j.isFuture),                 // isFuture
    bit(j.benchmark),                // benchmark
    order,                           // sort_order
  ].join(', ');
}

const out = [];
out.push('-- Auto-generated by scripts/build-migration.js — replaces D1 data with the JSON snapshot in /data.');
out.push('-- Import with:  wrangler d1 execute d1-template-database --remote --file=scripts/migrate.sql');
out.push('-- (or paste into the D1 Console). Editors are NOT touched (keys are not in the JSON).');
out.push('-- No BEGIN/COMMIT: D1 forbids SQL transaction statements and runs a --file batch atomically.');
out.push('');

// ── levels ──
const list = readJSON('_list.json');
out.push('DELETE FROM levels;');
let order = 0, missing = [];
for (const slug of list) {
  const file = path.join(DATA, slug + '.json');
  if (!fs.existsSync(file)) { missing.push(slug); continue; }
  const j = JSON.parse(fs.readFileSync(file, 'utf8'));
  order++;
  out.push(`INSERT INTO levels (${LEVEL_COLS.join(', ')}) VALUES (${levelValues(slug, j, order)});`);
}
out.push('');

// ── pending ──
const pending = readJSON('_pending.json');
out.push('DELETE FROM pending;');
for (const p of pending) {
  out.push(`INSERT INTO pending (name, placement, link, indefinite) VALUES (${s(p.name)}, ${s(p.placement)}, ${s(p.link)}, 0);`);
}
out.push('');

// ── config singletons ──
const lm = readJSON('_levelMonth.json');
const lv = readJSON('_levelVerif.json');
const upsert = (key, obj) =>
  `INSERT INTO config (key, value) VALUES (${q(key)}, ${q(JSON.stringify(obj))}) ` +
  `ON CONFLICT(key) DO UPDATE SET value = excluded.value;`;
out.push(upsert('levelMonth', lm));
out.push(upsert('levelVerif', lv));
out.push('');

fs.writeFileSync(OUT, out.join('\n') + '\n');

console.log(`Wrote ${OUT}`);
console.log(`  levels:  ${order} inserted (of ${list.length} in _list.json)`);
console.log(`  pending: ${pending.length}`);
console.log(`  config:  levelMonth + levelVerif`);
if (missing.length) console.log(`  ⚠ missing level files (skipped): ${missing.join(', ')}`);
